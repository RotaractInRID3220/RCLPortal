// Copies the drizzle-kit introspection output into src/server/db/schema.mjs (plain JS, with a header).
import { readFileSync, writeFileSync } from 'node:fs'
// drizzle-kit emits .default(') for an empty-string default; repair it.
const src = readFileSync('.drizzle-pull/schema.ts', 'utf8').replaceAll(".default(')", ".default('')")
const header = '// GENERATED by `npm run db:pull` (drizzle-kit introspection of the live schema). Do not hand-edit.\n' +
  '// The SQL files in db/migrations are the source of truth; re-run db:pull after each migration.\n'
writeFileSync('src/server/db/schema.mjs', header + src)
console.log('wrote src/server/db/schema.mjs')
